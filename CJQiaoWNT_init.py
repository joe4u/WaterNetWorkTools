    """
    This is an example algorithm that takes a vector layer and
    creates a new identical one.

    It is meant to be used as an example of how to create your own
    algorithms and explain methods and variables used to do it. An
    algorithm like this will be available in all elements, and there
    is not need for additional work.

    All Processing algorithms should extend the QgsProcessingAlgorithm
    class.
    """

    # Constants used to refer to parameters and outputs. They will be
    # used when calling the algorithm from another algorithm, or when
    # calling from the QGIS console.
    INPUT_LINE = 'INPUT_LINE'
    INPUT_NODE = 'INPUT_NODE'
    INPUT_SOURCE = 'INPUT_SOURCE'

    def initAlgorithm(self, config):
        """
        Here we define the inputs and output of the algorithm, along
        with some other properties.
        """
        
        # We add the input vector features source. It can have any kind of
        # geometry.
        #管线
        self.addParameter(
            QgsProcessingParameterVectorLayer(
                self.INPUT_LINE,
                self.tr('Input pip layer'),
                [QgsProcessing.TypeVectorLine]
            )
        )
        # #管线
        # self.addParameter(
        #     QgsProcessingParameterVectorLayer(
        #         self.INPUT_NODE,
        #         self.tr('Input node layer'),
        #         [QgsProcessing.TypeVectorPoint]
        #     )
        # )
        #水源
        self.addParameter(
            QgsProcessingParameterVectorLayer(
                self.INPUT_SOURCE,
                self.tr('Input  source layer'),
                [QgsProcessing.TypeVectorPoint]
            )
        )
    def processAlgorithm(self, parameters, context, feedback):
        """
        Here is where the processing itself takes place.
        """

        # Retrieve the feature source and sink. The 'dest_id' variable is used
        # to uniquely identify the feature sink, and must be included in the
        # dictionary returned by the processAlgorithm function.
        line = self.parameterAsVectorLayer(parameters, self.INPUT_LINE, context)
        # node = self.parameterAsVectorLayer(parameters, self.INPUT_NODE, context)
        source = self.parameterAsVectorLayer(parameters, self.INPUT_SOURCE, context)

        #开始编辑
        line.beginEditCommand("init isreverse and add root Feature")
        line.startEditing()
        
        #初始方向
        for feature in line.getFeatures():
            feature["isreverse"]="u"
            line.updateFeature(feature)
            # feedback.pushInfo('feature#: {0}.'.format(feature.id()))
            
            #line.changeAttributeValue(feature.id(), isrev_index,"u")
            #feature.setAttribute("isreverse","u")
       
        #return {self.OUTPUT: 111}
        
        #索引搜索
        line_index=QgsSpatialIndex(line.getFeatures())
        # 创建表达式过滤请求
        expression = QgsExpression('"isOpen" = true')
        request = QgsFeatureRequest(expression)
        sourcePoints = source.getFeatures()
        # feedback.pushInfo('sourcePoints#: {0}.'.format([item["isOpen"] for item in list(sourcePoints)]))
        sourceIndexs = []
        source_Points=[]
        for sourcePointFeature in sourcePoints:
            # feedback.pushInfo('sourcePoint#: {0}.'.format(sourcePointFeature["isOpen"]))
            # if sourcePointFeature["isOpen"]==False:
            #     continue
            sourcePoint=sourcePointFeature.geometry().asPoint()
            line_indexs =line_index.nearestNeighbor(sourcePoint)
        
            firstline=line.getFeature(line_indexs[0])
            sourceIndexs.append((str(firstline.id()),sourcePointFeature["isOpen"]))
            source_Points.append(sourcePoint)
        #合并所有源点为虚拟根源点
        #获取geometry为空的要素
        rootLine=next(line.getFeatures("$geometry IS NULL"),None)
        
        rootLine.setAttribute("isreverse","f")
        rootLine.setAttribute("isOpen",True)
        rootLine.setAttribute("source","")
        rootLine.setAttribute("target",','.join([item[0] for item in sourceIndexs if item[1]] ))
        # rootLine.setValid(True)
        # line.addFeature(rootLine)
        line.updateFeature(rootLine)

       
        # feedback.pushInfo('rootLine id#: {0}.'.format(rootLine.id()))

        for idx in range(len(sourceIndexs)):
            sourceIndex,isOpen=sourceIndexs[idx]
            # sourcePointFeature=source_Points[idx]
            sourcePoint=source_Points[idx]
            sourceGeo=line.getFeature(int(sourceIndex))

            linegeo=sourceGeo.geometry().constGet()
            # feedback.pushInfo('sourceGeo id#: {0}.'.format(QgsMultiLineString.geometryType()))
            if isinstance(linegeo, QgsMultiLineString):
                # QgsMultiLineString.childGeometry()
                linegeo=linegeo.lineStringN(0)
            startPoint=linegeo.startPoint()
            endPoint=linegeo.endPoint()
            
            dis_start=startPoint.distance(sourcePoint.x(),sourcePoint.y())
            dis_end=endPoint.distance(sourcePoint.x(),sourcePoint.y())
            strSource=','.join([str(rootLine.id())]+[item[0] for item in sourceIndexs if item[0]!=str(sourceIndex) and item[1]])
            feedback.pushInfo('strSource#: {0}.'.format(strSource))
            if(isOpen):            
                if (dis_start<dis_end):
                    # sourceGeo["isreverse"]="f" 
                    sourceGeo["source"]=strSource
                else:
                    # sourceGeo["isreverse"]="t"
                    sourceGeo["target"]=strSource
            else:
                if (dis_start<dis_end):
                    # sourceGeo["isreverse"]="t"
                    sourceGeo["source"]=""
                else:
                    # sourceGeo["isreverse"]="f"
                    sourceGeo["target"]=""
            line.updateFeature(sourceGeo)
        
        # line.commitChanges()
        WaterNetwork.InitDir([str(rootLine.id())],line,[-999],feedback)                
        line.commitChanges()
        line.endEditCommand()
        
        return {"result": "success!"}

